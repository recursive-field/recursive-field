def _yaml_scalar(value: object) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return json.dumps(str(value), ensure_ascii=False)


def _yaml_dump(value: object, indent: int = 0) -> list[str]:
    prefix = " " * indent
    lines: list[str] = []
    if isinstance(value, dict):
        for key, child in value.items():
            if isinstance(child, (dict, list)):
                lines.append(f"{prefix}{key}:")
                lines.extend(_yaml_dump(child, indent + 2))
            else:
                lines.append(f"{prefix}{key}: {_yaml_scalar(child)}")
    elif isinstance(value, list):
        for child in value:
            if isinstance(child, (dict, list)):
                lines.append(f"{prefix}-")
                lines.extend(_yaml_dump(child, indent + 2))
            else:
                lines.append(f"{prefix}- {_yaml_scalar(child)}")
    else:
        lines.append(f"{prefix}{_yaml_scalar(value)}")
    return lines


def _agent_service(agent: AgentNode, config: ResolvedConfig) -> dict[str, object]:
    slug = agent.slug
    host_root = config.field_root.as_posix()
    volumes = [
        f"{host_root}/agents/{slug}:/a0/agents/{slug}:ro",
        f"{host_root}/agents/{slug}/memory:/a0/memory:rw",
        f"{host_root}/agents/{slug}/observations:/a0/observations:rw",
        f"{host_root}/tmp/field_env.json:/a0/tmp/field_env.json:ro",
        f"{host_root}:/agent_orchestration:ro",
    ]
    volumes.extend(
        f"{host_root}/mesh/{mesh_slug}/queue.jsonl:"
        f"/a0/mesh/{mesh_slug}/queue.jsonl:rw"
        for mesh_slug in agent.mesh_slugs
    )
    return {
        "image": config.image_name,
        "container_name": agent.container_name,
        "environment": [
            "FIELD_ROOT=/agent_orchestration",
            f"AGENT_SLUG={slug}",
            f"AGENT_ID={agent.agent_id}",
        ],
        "expose": ["80"],
        "ports": [f"{agent.ssh_host_port}:22"],
        "volumes": volumes,
        "networks": ["field-bridge"],
        "restart": "unless-stopped",
    }


def _gateway_service(gateway: GatewayNode, config: ResolvedConfig) -> dict[str, object]:
    assert gateway.service_key is not None
    assert gateway.container_name is not None
    assert gateway.http_host_port is not None
    host_root = config.field_root.as_posix()
    return {
        "image": "nginx:latest",
        "container_name": gateway.container_name,
        "ports": [f"{gateway.http_host_port}:80"],
        "volumes": [
            f"{host_root}/gateways/{gateway.slug}/nginx.conf:"
            "/etc/nginx/nginx.conf:ro"
        ],
        "networks": ["field-bridge"],
        "restart": "unless-stopped",
        "depends_on": list(gateway.upstream_service_keys),
    }


def _render_compose(config: ResolvedConfig, topology: Topology) -> bytes:
    services: dict[str, object] = {}
    for agent in topology.agents:
        services[agent.service_key] = _agent_service(agent, config)
    for gateway in topology.gateways:
        if gateway.service_key is not None:
            services[gateway.service_key] = _gateway_service(gateway, config)
    spec = {
        "version": COMPOSE_VERSION,
        "services": services,
        "networks": {
            "field-bridge": {
                "name": f"{config.library}-bridge",
                "driver": "bridge",
            }
        },
    }
    text = GENERATED_MARKER + "\n" + "\n".join(_yaml_dump(spec)) + "\n"
    encoded = text.encode("utf-8")
    _validate_rendered_safety(encoded)
    return encoded


def _render_nginx(gateway: GatewayNode) -> bytes:
    if not gateway.upstream_service_keys:
        raise GenerationError(f"gateway {gateway.slug!r} has no upstream services")
    upstream_lines = "\n".join(
        f"    server {service_key}:80;" for service_key in gateway.upstream_service_keys
    )
    text = (
        f"{GENERATED_MARKER}\n"
        f"# gateway: {gateway.slug}\n"
        f"# target: {gateway.target_type}/{gateway.target_slug}\n\n"
        "events {}\n\n"
        "http {\n"
        "  upstream field_backend {\n"
        f"{upstream_lines}\n"
        "  }\n\n"
        "  server {\n"
        "    listen 80;\n\n"
        "    location / {\n"
        "      proxy_pass http://field_backend;\n"
        "      proxy_set_header Host $host;\n"
        "      proxy_set_header X-Real-IP $remote_addr;\n"
        "      proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n"
        "    }\n"
        "  }\n"
        "}\n"
    )
    encoded = text.encode("utf-8")
    _validate_rendered_safety(encoded)
    return encoded


def _validate_rendered_safety(content: bytes) -> None:
    if not content.startswith((GENERATED_MARKER + "\n").encode("utf-8")):
        raise GenerationError("generated output is missing the ownership marker")
    lowered = content.lower()
    if b"docker.sock" in lowered or b"/var/run/docker" in lowered:
        raise GenerationError("Docker socket references are forbidden")


