def _validate_output_path(root: Path, path: Path, label: str) -> None:
    absolute = path if path.is_absolute() else root / path
    absolute = Path(os.path.abspath(absolute))
    _assert_contained(root, absolute, label)
    if absolute == root:
        raise GenerationError(f"{label} must be a file beneath FIELD_ROOT")
    _assert_nonsymlink_chain(root, absolute, label)
    parent = absolute.parent
    if not parent.exists():
        raise GenerationError(f"{label} parent directory does not exist: {parent}")
    _assert_directory_nonsymlink(parent, f"{label} parent")
    if absolute.exists() or absolute.is_symlink():
        _assert_regular_nonsymlink(absolute, label)


def _digest(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def _is_owned(content: bytes) -> bool:
    return content.startswith((GENERATED_MARKER + "\n").encode("utf-8"))


def _directory_open_flags() -> int:
    return (
        os.O_RDONLY
        | getattr(os, "O_CLOEXEC", 0)
        | getattr(os, "O_DIRECTORY", 0)
        | getattr(os, "O_NOFOLLOW", 0)
    )


def _open_root_dirfd(root: Path) -> int:
    try:
        descriptor = os.open(root, _directory_open_flags())
    except OSError as exc:
        raise GenerationError(f"cannot safely open FIELD_ROOT directory: {root}: {exc}") from exc
    if not stat.S_ISDIR(os.fstat(descriptor).st_mode):
        os.close(descriptor)
        raise GenerationError(f"FIELD_ROOT is not a directory: {root}")
    return descriptor


def _open_parent_dirfd(root_fd: int, root: Path, path: Path, label: str) -> int:
    _assert_contained(root, path, label)
    relative_parent = path.relative_to(root).parent
    descriptor = os.dup(root_fd)
    try:
        for component in relative_parent.parts:
            if component in {"", ".", ".."} or "/" in component or "\\" in component:
                raise GenerationError(f"unsafe parent component in {label}: {component!r}")
            try:
                child = os.open(component, _directory_open_flags(), dir_fd=descriptor)
            except OSError as exc:
                raise GenerationError(
                    f"cannot safely traverse parent for {label}: {path}: {exc}"
                ) from exc
            os.close(descriptor)
            descriptor = child
        return descriptor
    except Exception:
        os.close(descriptor)
        raise


def _read_file_snapshot_at(
    parent_fd: int, name: str, label: str
) -> tuple[bytes, str, int, int, int]:
    flags = os.O_RDONLY | getattr(os, "O_CLOEXEC", 0) | getattr(os, "O_NOFOLLOW", 0)
    try:
        descriptor = os.open(name, flags, dir_fd=parent_fd)
    except OSError as exc:
        raise GenerationError(f"cannot safely open {label}: {name}: {exc}") from exc
    try:
        before = os.fstat(descriptor)
        if not stat.S_ISREG(before.st_mode):
            raise GenerationError(f"{label} must be a regular file: {name}")
        chunks: list[bytes] = []
        while True:
            chunk = os.read(descriptor, 1024 * 1024)
            if not chunk:
                break
            chunks.append(chunk)
        after = os.fstat(descriptor)
        if (before.st_dev, before.st_ino, before.st_size, before.st_mtime_ns) != (
            after.st_dev,
            after.st_ino,
            after.st_size,
            after.st_mtime_ns,
        ):
            raise GenerationError(f"{label} changed while being read: {name}")
        content = b"".join(chunks)
        return (
            content,
            _digest(content),
            after.st_dev,
            after.st_ino,
            stat.S_IMODE(after.st_mode),
        )
    finally:
        os.close(descriptor)


def _plan_write(
    root: Path,
    path: Path,
    content: bytes,
    *,
    require_owned: bool,
    adopt: bool,
) -> PlannedOutput:
    root_fd = _open_root_dirfd(root)
    parent_fd = _open_parent_dirfd(root_fd, root, path, "planned output")
    try:
        parent_stat = os.fstat(parent_fd)
        try:
            current, digest, device, inode, mode = _read_file_snapshot_at(
                parent_fd, path.name, "existing output"
            )
        except GenerationError as exc:
            try:
                os.stat(path.name, dir_fd=parent_fd, follow_symlinks=False)
            except FileNotFoundError:
                return PlannedOutput(
                    path, "create", content, None, False, None, None, None,
                    parent_stat.st_dev, parent_stat.st_ino,
                )
            raise exc
        owned = _is_owned(current)
        action = "unchanged" if current == content else "replace"
        if action == "replace" and require_owned and not owned and not adopt:
            raise GenerationError(
                f"refusing to overwrite unowned Nginx config {path}; use --adopt-existing"
            )
        return PlannedOutput(
            path, action, content, digest, owned, device, inode, mode,
            parent_stat.st_dev, parent_stat.st_ino,
        )
    finally:
        os.close(parent_fd)
        os.close(root_fd)


def _plan_delete(root: Path, path: Path, label: str) -> PlannedOutput | None:
    root_fd = _open_root_dirfd(root)
    parent_fd = _open_parent_dirfd(root_fd, root, path, label)
    try:
        parent_stat = os.fstat(parent_fd)
        try:
            current, digest, device, inode, mode = _read_file_snapshot_at(
                parent_fd, path.name, label
            )
        except GenerationError:
            try:
                os.stat(path.name, dir_fd=parent_fd, follow_symlinks=False)
            except FileNotFoundError:
                return None
            raise
        if not _is_owned(current):
            return None
        return PlannedOutput(
            path, "delete", None, digest, True, device, inode, mode,
            parent_stat.st_dev, parent_stat.st_ino,
        )
    finally:
        os.close(parent_fd)
        os.close(root_fd)


def _validate_unique_output_paths(paths: Sequence[Path]) -> None:
    seen: set[Path] = set()
    for path in paths:
        canonical = Path(os.path.abspath(path))
        if canonical in seen:
            raise GenerationError(f"duplicate planned output path: {canonical}")
        seen.add(canonical)


def plan_generation(
    *,
    out_path: str | os.PathLike[str] | None = None,
    port_base: int | str | None = None,
    image_name: str | None = None,
    library: str | None = None,
    field_root: str | os.PathLike[str] | None = None,
    start: str | os.PathLike[str] | None = None,
    environ: Mapping[str, str] | None = None,
    adopt_existing: bool = False,
) -> GenerationPlan:
    """Resolve, normalize, render, and return a mutation-free output plan."""
    config = _resolve_config(
        start=start,
        out_path=out_path,
        library=library,
        field_root=field_root,
        port_base=port_base,
        image_name=image_name,
        environ=environ,
    )
    topology = _normalize_topology(config)
    compose_bytes = _render_compose(config, topology)

    _validate_output_path(config.field_root, config.compose_path, "Compose output")
    write_specs: list[tuple[Path, bytes, bool, bool]] = [
        (config.compose_path, compose_bytes, False, True)
    ]
    nginx_rendered: list[tuple[str, bytes]] = []
    planned_nginx_paths: set[Path] = set()
    for gateway in topology.gateways:
        if gateway.service_key is None:
            continue
        nginx_path = gateway.source_dir / "nginx.conf"
        _validate_output_path(config.field_root, nginx_path, f"gateway {gateway.slug} Nginx output")
        content = _render_nginx(gateway)
        nginx_rendered.append((gateway.slug, content))
        planned_nginx_paths.add(nginx_path)
        write_specs.append((nginx_path, content, True, adopt_existing))

    # An inactive or non-HTTP gateway may retain an older generated config.
    # Delete only files that prove generator ownership with the exact marker.
    delete_paths: list[tuple[Path, str]] = []
    for gateway in topology.gateways:
        nginx_path = gateway.source_dir / "nginx.conf"
        if nginx_path in planned_nginx_paths or not nginx_path.exists():
            continue
        label = f"stale gateway {gateway.slug} Nginx output"
        _validate_output_path(config.field_root, nginx_path, label)
        delete_paths.append((nginx_path, label))

    # Reject aliases/collisions before reading ownership state or staging bytes.
    _validate_unique_output_paths(
        [path for path, *_ in write_specs] + [path for path, _label in delete_paths]
    )
    outputs = [
        _plan_write(
            config.field_root,
            path,
            content,
            require_owned=require_owned,
            adopt=adopt,
        )
        for path, content, require_owned, adopt in write_specs
    ]
    for path, label in delete_paths:
        deletion = _plan_delete(config.field_root, path, label)
        if deletion is not None:
            outputs.append(deletion)

    outputs.sort(key=lambda output: str(output.path.relative_to(config.field_root)))
    nginx_rendered.sort(key=lambda item: item[0])
    return GenerationPlan(
        config=config,
        topology=topology,
        outputs=tuple(outputs),
        compose_bytes=compose_bytes,
        nginx_bytes=tuple(nginx_rendered),
    )


def _preflight_output_at(output: PlannedOutput, parent_fd: int) -> None:
    if output.prior_digest is None:
        try:
            os.stat(output.path.name, dir_fd=parent_fd, follow_symlinks=False)
        except FileNotFoundError:
            return
        raise GenerationError(f"output appeared after planning: {output.path}")
    current, digest, device, inode, mode = _read_file_snapshot_at(
        parent_fd, output.path.name, "planned output"
    )
    if (
        digest != output.prior_digest
        or device != output.prior_device
        or inode != output.prior_inode
        or mode != output.prior_mode
    ):
        raise GenerationError(f"output identity or content changed after planning: {output.path}")
    if output.action == "delete" and not _is_owned(current):
        raise GenerationError(f"stale output lost its ownership marker: {output.path}")


def _verify_parent_binding(
    root_fd: int,
    root: Path,
    output: PlannedOutput,
    pinned_parent_fd: int,
) -> None:
    pinned = os.fstat(pinned_parent_fd)
    if (pinned.st_dev, pinned.st_ino) != (output.parent_device, output.parent_inode):
        raise GenerationError(f"pinned output parent identity changed: {output.path.parent}")
    current_fd = _open_parent_dirfd(root_fd, root, output.path, "planned output parent")
    try:
        current = os.fstat(current_fd)
        if (current.st_dev, current.st_ino) != (
            output.parent_device,
            output.parent_inode,
        ):
            raise GenerationError(
                f"output parent was replaced after planning: {output.path.parent}"
            )
    finally:
        os.close(current_fd)


def _stage_output(output: PlannedOutput, parent_fd: int) -> str:
    assert output.content is not None
    existing_mode = output.prior_mode if output.prior_mode is not None else 0o644
    descriptor = -1
    staged_name = ""
    for _attempt in range(100):
        candidate = f".{output.path.name}.{uuid.uuid4().hex}.tmp"
        try:
            descriptor = os.open(
                candidate,
                os.O_WRONLY
                | os.O_CREAT
                | os.O_EXCL
                | getattr(os, "O_CLOEXEC", 0)
                | getattr(os, "O_NOFOLLOW", 0),
                existing_mode,
                dir_fd=parent_fd,
            )
            staged_name = candidate
            break
        except FileExistsError:
            continue
    if descriptor < 0:
        raise GenerationError(f"could not allocate staging file for {output.path}")
    try:
        with os.fdopen(descriptor, "wb") as handle:
            descriptor = -1
            handle.write(output.content)
            handle.flush()
            os.fsync(handle.fileno())
            os.fchmod(handle.fileno(), existing_mode)
        return staged_name
    except Exception:
        if descriptor >= 0:
            os.close(descriptor)
        try:
            os.unlink(staged_name, dir_fd=parent_fd)
        except FileNotFoundError:
            pass
        raise


def _cleanup_staged(parent_fd: int, staged_name: str) -> None:
    try:
        os.unlink(staged_name, dir_fd=parent_fd)
    except FileNotFoundError:
        pass


def apply_plan(plan: GenerationPlan) -> None:
    """Apply a plan through FIELD_ROOT-rooted, no-follow parent directory FDs.

    All replacement bytes are staged and fsynced before the first mutation.
    Parent identity and final-file state are revalidated immediately before each
    dirfd-relative replace/delete. Each replacement is atomic; there is no
    cross-file atomic transaction.
    """
    mutations = plan.mutations
    root_fd = _open_root_dirfd(plan.config.field_root)
    parents: dict[Path, int] = {}
    staged: dict[Path, str] = {}
    try:
        for output in mutations:
            parent_fd = _open_parent_dirfd(
                root_fd, plan.config.field_root, output.path, "planned output"
            )
            parents[output.path] = parent_fd
            _verify_parent_binding(
                root_fd, plan.config.field_root, output, parent_fd
            )
            _preflight_output_at(output, parent_fd)

        for output in mutations:
            if output.action in {"create", "replace"}:
                staged[output.path] = _stage_output(output, parents[output.path])

        for output in mutations:
            parent_fd = parents[output.path]
            _verify_parent_binding(
                root_fd, plan.config.field_root, output, parent_fd
            )
            _preflight_output_at(output, parent_fd)
            if output.action in {"create", "replace"}:
                staged_name = staged[output.path]
                os.replace(
                    staged_name,
                    output.path.name,
                    src_dir_fd=parent_fd,
                    dst_dir_fd=parent_fd,
                )
                staged.pop(output.path)
                os.fsync(parent_fd)
            elif output.action == "delete":
                os.unlink(output.path.name, dir_fd=parent_fd)
                os.fsync(parent_fd)
    finally:
        for path, staged_name in staged.items():
            parent_fd = parents.get(path)
            if parent_fd is not None:
                _cleanup_staged(parent_fd, staged_name)
        for parent_fd in parents.values():
            os.close(parent_fd)
        os.close(root_fd)


def _result_dict(plan: GenerationPlan, dry_run: bool) -> dict[str, object]:
    active_gateways = [item for item in plan.topology.gateways if item.service_key]
    return {
        "field_root": str(plan.config.field_root),
        "env_path": str(plan.config.field_root / ".env"),
        "compose_path": str(plan.config.compose_path),
        "library": plan.config.library,
        "port_base": plan.config.port_base,
        "image_name": plan.config.image_name,
        "dry_run": dry_run,
        "total_services": len(plan.topology.agents) + len(active_gateways),
        "agent_services": len(plan.topology.agents),
        "nginx_services": len(active_gateways),
        "service_names": [
            *(item.service_key for item in plan.topology.agents),
            *(item.service_key for item in active_gateways if item.service_key),
        ],
        "nginx_configs": [
            str(item.source_dir / "nginx.conf") for item in active_gateways
        ],
        "actions": [
            {
                "action": output.action,
                "path": str(output.path),
                "sha256": _digest(output.content) if output.content is not None else None,
            }
            for output in plan.outputs
        ],
        "compose_bytes": plan.compose_bytes,
        "nginx_bytes": dict(plan.nginx_bytes),
        "plan": plan,
    }


def generate_compose(
    out_path: str | os.PathLike[str] | None = None,
    port_base: int | str | None = None,
    image_name: str | None = None,
    start: str | os.PathLike[str] | None = None,
    *,
    library: str | None = None,
    field_root: str | os.PathLike[str] | None = None,
    environ: Mapping[str, str] | None = None,
    dry_run: bool = False,
    adopt_existing: bool = False,
) -> dict[str, object]:
    """Generate Compose and gateway Nginx files without modifying ``.env``."""
    plan = plan_generation(
        out_path=out_path,
        port_base=port_base,
        image_name=image_name,
        library=library,
        field_root=field_root,
        start=start,
        environ=environ,
        adopt_existing=adopt_existing,
    )
    if not dry_run:
        apply_plan(plan)
    return _result_dict(plan, dry_run)


def _print_result(result: Mapping[str, object]) -> None:
    mode = "DRY RUN" if result["dry_run"] else "APPLIED"
    print(f"{mode}: {result['field_root']}")
    print(f"Compose: {result['compose_path']}")
    print(f"Library: {result['library']}")
    print(f"Port Base: {result['port_base']}")
    print(
        f"Services: {result['agent_services']} agents, "
        f"{result['nginx_services']} nginx"
    )
    for action in result["actions"]:  # type: ignore[union-attr]
        print(f"  {action['action']}: {action['path']}")


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Validate topology and generate owned Compose/Nginx outputs"
    )
    parser.add_argument(
        "--out",
        help="compatibility spelling; must resolve exactly to FIELD_ROOT/docker-compose.yml",
    )
    parser.add_argument("--library", help="explicit LIBRARY override")
    parser.add_argument("--field-root", help="explicit FIELD_ROOT (must match discovery)")
    parser.add_argument("--port-base", help="explicit PORT_BASE override")
    parser.add_argument("--image", dest="image_name", help="agent image override")
    parser.add_argument(
        "--start", help="path from which to discover .recursive-field-root"
    )
    parser.add_argument(
        "--dry-run", action="store_true", help="validate and report without mutation"
    )
    parser.add_argument(
        "--adopt-existing",
        action="store_true",
        help="explicitly replace an unmarked Nginx config at an active gateway",
    )
    args = parser.parse_args(argv)
    try:
        result = generate_compose(
            out_path=args.out,
            port_base=args.port_base,
            image_name=args.image_name,
            start=args.start,
            library=args.library,
            field_root=args.field_root,
            dry_run=args.dry_run,
            adopt_existing=args.adopt_existing,
        )
    except (GenerationError, OSError) as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 2
    _print_result(result)
    return 0


