#!/usr/bin/env python3
"""Validate Recursive Field topology and generate owned Compose/Nginx outputs.

The root ``.env`` file is an operator-owned, read-only input.  Generation is
split into resolution, normalization, rendering, planning, and application so
all validation completes before any output is changed.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import stat
import sys
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import Mapping, Sequence

_THIS_DIR = Path(__file__).resolve().parent
if str(_THIS_DIR) not in sys.path:
    sys.path.insert(0, str(_THIS_DIR))

from find_root import find_root  # noqa: E402

GENERATED_MARKER = "# GENERATED BY RECURSIVE_FIELD — DO NOT EDIT DIRECTLY"
MARKER_FILENAME = ".recursive-field-root"
DEFAULT_LIBRARY = "recursive-field"
DEFAULT_PORT_BASE = 44000
DEFAULT_IMAGE = "agent0ai/agent-zero:latest"
COMPOSE_VERSION = "3.8"
SUPPORTED_TOPOLOGY_SCHEMA_VERSIONS = frozenset({"1.0.0"})
SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
SERVICE_KEY_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")
VALID_GATEWAY_TYPES = frozenset({"api", "cli", "http"})
VALID_GATEWAY_STATUSES = frozenset({"active", "inactive"})
HTTP_GATEWAY_TYPES = frozenset({"api", "http"})


class GenerationError(ValueError):
    """Raised when inputs cannot produce a safe deterministic generation."""


@dataclass(frozen=True)
class ResolvedConfig:
    library: str
    field_root: Path
    port_base: int
    image_name: str
    compose_path: Path


@dataclass(frozen=True)
class AgentNode:
    slug: str
    agent_id: str
    role: str
    source_dir: Path
    service_key: str
    container_name: str
    ssh_host_port: int
    mesh_slugs: tuple[str, ...]


@dataclass(frozen=True)
class MeshNode:
    slug: str
    mesh_id: str
    source_dir: Path
    endpoints: tuple[str, ...]


@dataclass(frozen=True)
class GatewayNode:
    slug: str
    gateway_id: str
    source_dir: Path
    target_type: str
    target_slug: str
    target_id: str
    gateway_type: str
    status: str
    service_key: str | None
    container_name: str | None
    upstream_service_keys: tuple[str, ...]
    http_host_port: int | None


@dataclass(frozen=True)
class Topology:
    genesis_uuid: str
    schema_version: str
    agents: tuple[AgentNode, ...]
    meshes: tuple[MeshNode, ...]
    gateways: tuple[GatewayNode, ...]


@dataclass(frozen=True)
class PlannedOutput:
    path: Path
    action: str
    content: bytes | None
    prior_digest: str | None
    owned: bool
    prior_device: int | None
    prior_inode: int | None
    prior_mode: int | None
    parent_device: int
    parent_inode: int


@dataclass(frozen=True)
class GenerationPlan:
    config: ResolvedConfig
    topology: Topology
    outputs: tuple[PlannedOutput, ...]
    compose_bytes: bytes
    nginx_bytes: tuple[tuple[str, bytes], ...]

    @property
    def mutations(self) -> tuple[PlannedOutput, ...]:
        return tuple(output for output in self.outputs if output.action != "unchanged")


# ---------------------------------------------------------------------------
# Scalar, path, and input validation


def _canonical_uuid(value: object, label: str) -> str:
    if not isinstance(value, str):
        raise GenerationError(f"{label} must be a canonical UUID string")
    try:
        parsed = uuid.UUID(value)
    except (ValueError, AttributeError) as exc:
        raise GenerationError(f"{label} is not a valid UUID: {value!r}") from exc
    canonical = str(parsed)
    if value != canonical:
        raise GenerationError(f"{label} must use canonical lowercase UUID form")
    return canonical


def _validated_slug(value: object, label: str) -> str:
    if not isinstance(value, str) or not SLUG_RE.fullmatch(value):
        raise GenerationError(
            f"{label} must use lowercase alphanumerics separated by single hyphens"
        )
    if value in {".", ".."} or "/" in value or "\\" in value:
        raise GenerationError(f"{label} contains a forbidden path coordinate")
    return value


def _required_string(data: Mapping[str, object], key: str, label: str) -> str:
    value = data.get(key)
    if not isinstance(value, str) or not value:
        raise GenerationError(f"{label}.{key} must be a nonempty string")
    if "\n" in value or "\r" in value:
        raise GenerationError(f"{label}.{key} contains a newline")
    return value


def _parse_port_base(value: object) -> int:
    if isinstance(value, bool):
        raise GenerationError("PORT_BASE must be an integer")
    if isinstance(value, int):
        parsed = value
    elif isinstance(value, str) and re.fullmatch(r"[0-9]+", value):
        parsed = int(value, 10)
    else:
        raise GenerationError(f"PORT_BASE must be an integer, got {value!r}")
    if not 1 <= parsed <= 65535:
        raise GenerationError("PORT_BASE must be within 1..65535")
    return parsed


def _derived_port(value: int, label: str, allocated: dict[int, str]) -> int:
    if not 1 <= value <= 65535:
        raise GenerationError(f"{label} derived port {value} is outside 1..65535")
    previous = allocated.get(value)
    if previous is not None:
        raise GenerationError(
            f"host port collision: {label} and {previous} both allocate {value}"
        )
    allocated[value] = label
    return value


def _read_env(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    _assert_regular_nonsymlink(path, ".env")
    values: dict[str, str] = {}
    for line_number, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[7:].lstrip()
        if "=" not in line:
            raise GenerationError(f"invalid .env assignment at line {line_number}")
        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip()
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", key):
            raise GenerationError(f"invalid .env key at line {line_number}: {key!r}")
        if key in values:
            raise GenerationError(f"duplicate .env assignment for {key}")
        if len(value) >= 2 and value[0] == value[-1] and value[0] in {"'", '"'}:
            value = value[1:-1]
        values[key] = value
    return values


def _assert_regular_nonsymlink(path: Path, label: str) -> None:
    try:
        mode = path.lstat().st_mode
    except FileNotFoundError as exc:
        raise GenerationError(f"missing {label}: {path}") from exc
    if stat.S_ISLNK(mode) or not stat.S_ISREG(mode):
        raise GenerationError(f"{label} must be a regular non-symlink file: {path}")


def _assert_directory_nonsymlink(path: Path, label: str) -> None:
    try:
        mode = path.lstat().st_mode
    except FileNotFoundError as exc:
        raise GenerationError(f"missing {label}: {path}") from exc
    if stat.S_ISLNK(mode) or not stat.S_ISDIR(mode):
        raise GenerationError(f"{label} must be a real directory, not a symlink: {path}")


def _assert_contained(root: Path, path: Path, label: str) -> None:
    try:
        path.relative_to(root)
    except ValueError as exc:
        raise GenerationError(f"{label} escapes FIELD_ROOT: {path}") from exc


def _assert_nonsymlink_chain(root: Path, path: Path, label: str) -> None:
    _assert_contained(root, path, label)
    relative = path.relative_to(root)
    current = root
    for part in relative.parts:
        if part in {"", ".", ".."}:
            raise GenerationError(f"unsafe component in {label}: {part!r}")
        current = current / part
        if current.exists() or current.is_symlink():
            if stat.S_ISLNK(current.lstat().st_mode):
                raise GenerationError(f"symlink is forbidden for {label}: {current}")


def _read_json(path: Path, root: Path, label: str) -> dict[str, object]:
    _assert_nonsymlink_chain(root, path, label)
    _assert_regular_nonsymlink(path, label)
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise GenerationError(f"invalid JSON in {label}: {path}: {exc}") from exc
    if not isinstance(value, dict):
        raise GenerationError(f"{label} must contain a JSON object")
    return value


def _resolve_candidate_path(value: object, root: Path, label: str) -> Path:
    if not isinstance(value, (str, os.PathLike)) or not str(value):
        raise GenerationError(f"{label} must be a nonempty path")
    candidate = Path(value).expanduser()
    if not candidate.is_absolute():
        candidate = root / candidate
    return candidate.resolve(strict=False)


def _resolve_config(
    *,
    start: str | os.PathLike[str] | None,
    out_path: str | os.PathLike[str] | None,
    library: str | None,
    field_root: str | os.PathLike[str] | None,
    port_base: int | str | None,
    image_name: str | None,
    environ: Mapping[str, str] | None,
) -> ResolvedConfig:
    discovered = find_root(start)
    if discovered is None:
        raise GenerationError(
            "could not discover FIELD_ROOT from a .recursive-field-root marker"
        )
    root = discovered.resolve(strict=True)
    _assert_directory_nonsymlink(root, "FIELD_ROOT")
    marker_path = root / MARKER_FILENAME
    _assert_regular_nonsymlink(marker_path, "field marker")

    env = os.environ if environ is None else environ
    dotenv = _read_env(root / ".env")

    # FIELD_ROOT is identity-bearing: every supplied source must agree with
    # marker discovery even when a higher-precedence source wins.
    root_sources: list[tuple[str, object]] = []
    if field_root is not None:
        root_sources.append(("explicit FIELD_ROOT", field_root))
    if env.get("FIELD_ROOT", ""):
        root_sources.append(("environment FIELD_ROOT", env["FIELD_ROOT"]))
    if dotenv.get("FIELD_ROOT", ""):
        root_sources.append((".env FIELD_ROOT", dotenv["FIELD_ROOT"]))
    for source, value in root_sources:
        candidate = _resolve_candidate_path(value, root, source)
        if candidate != root:
            raise GenerationError(
                f"{source} conflicts with marker-discovered FIELD_ROOT: "
                f"{candidate} != {root}"
            )

    selected_library: object
    if library is not None:
        selected_library = library
    elif env.get("LIBRARY", ""):
        selected_library = env["LIBRARY"]
    elif dotenv.get("LIBRARY", ""):
        selected_library = dotenv["LIBRARY"]
    else:
        selected_library = DEFAULT_LIBRARY
    selected_library = _validated_slug(selected_library, "LIBRARY")

    if port_base is not None:
        selected_port: object = port_base
    elif env.get("PORT_BASE", ""):
        selected_port = env["PORT_BASE"]
    elif dotenv.get("PORT_BASE", ""):
        selected_port = dotenv["PORT_BASE"]
    else:
        selected_port = DEFAULT_PORT_BASE
    selected_port_base = _parse_port_base(selected_port)

    if image_name is not None:
        selected_image = image_name
    elif env.get("IMAGE_NAME", ""):
        selected_image = env["IMAGE_NAME"]
    elif dotenv.get("IMAGE_NAME", ""):
        selected_image = dotenv["IMAGE_NAME"]
    else:
        selected_image = DEFAULT_IMAGE
    if not selected_image or "\n" in selected_image or "\r" in selected_image:
        raise GenerationError("IMAGE_NAME must be a nonempty single-line value")

    compose_path = root / "docker-compose.yml"
    if out_path is not None:
        raw_output = Path(out_path)
        requested = raw_output if raw_output.is_absolute() else root / raw_output
        requested = Path(os.path.abspath(requested))
        if requested != compose_path:
            raise GenerationError(
                "Compose output is fixed at FIELD_ROOT/docker-compose.yml; "
                "--out may name only that canonical path"
            )
    _validate_output_path(root, compose_path, "Compose output")

    return ResolvedConfig(
        library=selected_library,
        field_root=root,
        port_base=selected_port_base,
        image_name=selected_image,
        compose_path=compose_path,
    )


# ---------------------------------------------------------------------------
# Normalized topology


def _scan_manifest_dirs(root: Path, directory: str, filename: str) -> list[tuple[Path, dict[str, object]]]:
    base = root / directory
    _assert_nonsymlink_chain(root, base, directory)
    _assert_directory_nonsymlink(base, directory)
    found: list[tuple[Path, dict[str, object]]] = []
    for entry in sorted(base.iterdir(), key=lambda item: item.name):
        if entry.is_symlink():
            raise GenerationError(f"symlinked {directory} coordinate is forbidden: {entry}")
        if not entry.is_dir():
            continue
        _validated_slug(entry.name, f"{directory} directory name")
        manifest = entry / filename
        found.append((entry, _read_json(manifest, root, f"{directory}/{entry.name}/{filename}")))
    return found


def _validate_common_manifest(
    data: Mapping[str, object],
    *,
    directory: Path,
    id_key: str,
    label: str,
    genesis_uuid: str,
    schema_version: str,
) -> tuple[str, str]:
    slug = _validated_slug(data.get("slug"), f"{label}.slug")
    if slug != directory.name:
        raise GenerationError(
            f"{label} slug/directory mismatch: {slug!r} != {directory.name!r}"
        )
    object_id = _canonical_uuid(data.get(id_key), f"{label}.{id_key}")
    manifest_genesis = _canonical_uuid(
        data.get("field_genesis_uuid"), f"{label}.field_genesis_uuid"
    )
    if manifest_genesis != genesis_uuid:
        raise GenerationError(f"{label} field_genesis_uuid does not match field marker")
    if data.get("schema_version") != schema_version:
        raise GenerationError(f"{label} schema_version does not match field marker")
    return slug, object_id


def _normalize_topology(config: ResolvedConfig) -> Topology:
    root = config.field_root
    marker = _read_json(root / MARKER_FILENAME, root, "field marker")
    genesis_uuid = _canonical_uuid(marker.get("genesis_uuid"), "field marker.genesis_uuid")
    schema_version = _required_string(marker, "schema_version", "field marker")
    if schema_version not in SUPPORTED_TOPOLOGY_SCHEMA_VERSIONS:
        supported = ", ".join(sorted(SUPPORTED_TOPOLOGY_SCHEMA_VERSIONS))
        raise GenerationError(
            f"unsupported topology schema_version {schema_version!r}; supported: {supported}"
        )

    raw_agents = _scan_manifest_dirs(root, "agents", "identity.json")
    provisional_agents: list[tuple[str, str, str, Path]] = []
    agent_ids: set[str] = set()
    agent_slugs: set[str] = set()
    all_object_ids: set[str] = set()
    all_object_slugs: set[str] = set()
    for directory, identity in raw_agents:
        label = f"agent {directory.name!r}"
        slug, agent_id = _validate_common_manifest(
            identity,
            directory=directory,
            id_key="agent_id",
            label=label,
            genesis_uuid=genesis_uuid,
            schema_version=schema_version,
        )
        if slug in agent_slugs:
            raise GenerationError(f"duplicate agent slug: {slug}")
        if agent_id in agent_ids:
            raise GenerationError(f"duplicate agent_id: {agent_id}")
        if agent_id in all_object_ids:
            raise GenerationError(f"duplicate topology object ID: {agent_id}")
        if slug in all_object_slugs:
            raise GenerationError(f"duplicate topology slug: {slug}")
        agent_slugs.add(slug)
        agent_ids.add(agent_id)
        all_object_ids.add(agent_id)
        all_object_slugs.add(slug)
        role = _required_string(identity, "role", label)
        for mutable_name in ("memory", "observations"):
            mutable_path = directory / mutable_name
            _assert_nonsymlink_chain(root, mutable_path, f"agent {slug} {mutable_name}")
            _assert_directory_nonsymlink(mutable_path, f"agent {slug} {mutable_name}")
        provisional_agents.append((slug, agent_id, role, directory))
    provisional_agents.sort(key=lambda item: (item[0], item[1]))

    raw_meshes = _scan_manifest_dirs(root, "mesh", "channel.json")
    meshes: list[MeshNode] = []
    mesh_ids: set[str] = set()
    mesh_slugs: set[str] = set()
    agent_id_by_slug = {slug: agent_id for slug, agent_id, _, _ in provisional_agents}
    agent_meshes: dict[str, list[str]] = {slug: [] for slug in agent_id_by_slug}
    for directory, channel in raw_meshes:
        label = f"mesh {directory.name!r}"
        slug, mesh_id = _validate_common_manifest(
            channel,
            directory=directory,
            id_key="mesh_id",
            label=label,
            genesis_uuid=genesis_uuid,
            schema_version=schema_version,
        )
        if slug in mesh_slugs:
            raise GenerationError(f"duplicate mesh slug: {slug}")
        if mesh_id in mesh_ids:
            raise GenerationError(f"duplicate mesh_id: {mesh_id}")
        if mesh_id in all_object_ids:
            raise GenerationError(f"duplicate topology object ID: {mesh_id}")
        if slug in all_object_slugs:
            raise GenerationError(f"duplicate topology slug: {slug}")
        mesh_slugs.add(slug)
        mesh_ids.add(mesh_id)
        all_object_ids.add(mesh_id)
        all_object_slugs.add(slug)
        endpoints = channel.get("endpoints")
        if not isinstance(endpoints, list) or len(endpoints) < 2:
            raise GenerationError(f"{label} must define at least two endpoints")
        normalized_endpoints: list[str] = []
        seen_endpoints: set[str] = set()
        for index, endpoint in enumerate(endpoints):
            if not isinstance(endpoint, dict):
                raise GenerationError(f"{label}.endpoints[{index}] must be an object")
            endpoint_slug = _validated_slug(
                endpoint.get("slug"), f"{label}.endpoints[{index}].slug"
            )
            endpoint_id = _canonical_uuid(
                endpoint.get("agent_id"), f"{label}.endpoints[{index}].agent_id"
            )
            if endpoint_slug not in agent_id_by_slug:
                raise GenerationError(f"{label} references unknown agent {endpoint_slug!r}")
            if endpoint_id != agent_id_by_slug[endpoint_slug]:
                raise GenerationError(f"{label} endpoint ID mismatch for {endpoint_slug!r}")
            if endpoint_slug in seen_endpoints:
                raise GenerationError(f"{label} has duplicate endpoint {endpoint_slug!r}")
            seen_endpoints.add(endpoint_slug)
            normalized_endpoints.append(endpoint_slug)
            agent_meshes[endpoint_slug].append(slug)
        queue_path = directory / "queue.jsonl"
        _assert_nonsymlink_chain(root, queue_path, f"mesh {slug} queue")
        _assert_regular_nonsymlink(queue_path, f"mesh {slug} queue")
        meshes.append(
            MeshNode(
                slug=slug,
                mesh_id=mesh_id,
                source_dir=directory,
                endpoints=tuple(sorted(normalized_endpoints)),
            )
        )
    meshes.sort(key=lambda item: (item.slug, item.mesh_id))

    allocated_ports: dict[int, str] = {}
    agents: list[AgentNode] = []
    service_keys: set[str] = set()
    container_names: set[str] = set()
    for index, (slug, agent_id, role, directory) in enumerate(provisional_agents):
        service_key = f"agent-{slug}"
        container_name = f"{config.library}-{slug}"
        _validate_unique_runtime_name(
            service_key, container_name, service_keys, container_names, f"agent {slug}"
        )
        slot = config.port_base + index * 100
        ssh_port = _derived_port(slot + 22, f"agent {slug} SSH", allocated_ports)
        agents.append(
            AgentNode(
                slug=slug,
                agent_id=agent_id,
                role=role,
                source_dir=directory,
                service_key=service_key,
                container_name=container_name,
                ssh_host_port=ssh_port,
                mesh_slugs=tuple(sorted(agent_meshes[slug])),
            )
        )

    agents_by_slug = {agent.slug: agent for agent in agents}
    meshes_by_slug = {mesh.slug: mesh for mesh in meshes}

    raw_gateways = _scan_manifest_dirs(root, "gateways", "manifest.json")
    provisional_gateways: list[tuple[Path, dict[str, object], str, str]] = []
    gateway_ids: set[str] = set()
    gateway_slugs: set[str] = set()
    for directory, manifest in raw_gateways:
        label = f"gateway {directory.name!r}"
        slug, gateway_id = _validate_common_manifest(
            manifest,
            directory=directory,
            id_key="gateway_id",
            label=label,
            genesis_uuid=genesis_uuid,
            schema_version=schema_version,
        )
        if slug in gateway_slugs:
            raise GenerationError(f"duplicate gateway slug: {slug}")
        if gateway_id in gateway_ids:
            raise GenerationError(f"duplicate gateway_id: {gateway_id}")
        if gateway_id in all_object_ids:
            raise GenerationError(f"duplicate topology object ID: {gateway_id}")
        if slug in all_object_slugs:
            raise GenerationError(f"duplicate topology slug: {slug}")
        gateway_slugs.add(slug)
        gateway_ids.add(gateway_id)
        all_object_ids.add(gateway_id)
        all_object_slugs.add(slug)
        provisional_gateways.append((directory, manifest, slug, gateway_id))
    provisional_gateways.sort(key=lambda item: (item[2], item[3]))

    gateways: list[GatewayNode] = []
    active_http_index = 0
    for directory, manifest, slug, gateway_id in provisional_gateways:
        label = f"gateway {slug!r}"
        target_type = _required_string(manifest, "target_type", label)
        if target_type not in {"agent", "mesh"}:
            raise GenerationError(f"{label} has invalid target_type {target_type!r}")
        target_slug = _validated_slug(manifest.get("target_slug"), f"{label}.target_slug")
        target_id = _canonical_uuid(manifest.get("target_id"), f"{label}.target_id")
        if target_type == "agent":
            target = agents_by_slug.get(target_slug)
            if target is None:
                raise GenerationError(f"{label} targets unknown agent {target_slug!r}")
            expected_target_id = target.agent_id
            upstreams = (target.service_key,)
        else:
            target = meshes_by_slug.get(target_slug)
            if target is None:
                raise GenerationError(f"{label} targets unknown mesh {target_slug!r}")
            expected_target_id = target.mesh_id
            upstreams = tuple(agents_by_slug[item].service_key for item in target.endpoints)
        if target_id != expected_target_id:
            raise GenerationError(f"{label} target_id does not match {target_type} target")
        gateway_type = _required_string(manifest, "gateway_type", label)
        if gateway_type not in VALID_GATEWAY_TYPES:
            raise GenerationError(f"{label} has unsupported gateway_type {gateway_type!r}")
        status = _required_string(manifest, "status", label)
        if status not in VALID_GATEWAY_STATUSES:
            raise GenerationError(f"{label} has invalid status {status!r}")

        service_key: str | None = None
        container_name: str | None = None
        http_port: int | None = None
        normalized_upstreams: tuple[str, ...] = ()
        if status == "active" and gateway_type in HTTP_GATEWAY_TYPES:
            normalized_upstreams = tuple(sorted(upstreams))
            if not normalized_upstreams or len(set(normalized_upstreams)) != len(normalized_upstreams):
                raise GenerationError(f"{label} has empty or duplicate upstreams")
            if any(key not in service_keys for key in normalized_upstreams):
                raise GenerationError(f"{label} contains an unresolved upstream service key")
            service_key = f"nginx-{slug}"
            container_name = f"{config.library}-{slug}"
            _validate_unique_runtime_name(
                service_key,
                container_name,
                service_keys,
                container_names,
                f"gateway {slug}",
            )
            slot = config.port_base + (len(agents) + active_http_index) * 100
            http_port = _derived_port(
                slot + 80, f"gateway {slug} HTTP", allocated_ports
            )
            active_http_index += 1
        gateways.append(
            GatewayNode(
                slug=slug,
                gateway_id=gateway_id,
                source_dir=directory,
                target_type=target_type,
                target_slug=target_slug,
                target_id=target_id,
                gateway_type=gateway_type,
                status=status,
                service_key=service_key,
                container_name=container_name,
                upstream_service_keys=normalized_upstreams,
                http_host_port=http_port,
            )
        )

    return Topology(
        genesis_uuid=genesis_uuid,
        schema_version=schema_version,
        agents=tuple(agents),
        meshes=tuple(meshes),
        gateways=tuple(gateways),
    )


def _validate_unique_runtime_name(
    service_key: str,
    container_name: str,
    service_keys: set[str],
    container_names: set[str],
    label: str,
) -> None:
    if not SERVICE_KEY_RE.fullmatch(service_key):
        raise GenerationError(f"invalid Compose service key for {label}: {service_key!r}")
    if service_key in service_keys:
        raise GenerationError(f"duplicate Compose service key: {service_key}")
    if container_name in container_names:
        raise GenerationError(f"duplicate container name: {container_name}")
    service_keys.add(service_key)
    container_names.add(container_name)


